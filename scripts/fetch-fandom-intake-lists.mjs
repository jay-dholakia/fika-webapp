async function fetchArtists() {
  const seen = new Set()
  const names = []
  const terms = [
    'pop',
    'rock',
    'hip hop',
    'country',
    'jazz',
    'r&b',
    'electronic',
    'latin',
    'metal',
    'indie',
    'folk',
    'blues',
    'reggae',
    'k-pop',
    'classical',
    'soul',
    'punk',
    'alternative',
    'dance',
    'rap',
    'singer',
    'band',
    'orchestra',
    'gospel',
    'edm',
    'trap',
    'house',
    'techno',
  ]
  for (const term of terms) {
    if (names.length >= 500) break
    const url = `https://itunes.apple.com/search?term=${encodeURIComponent(term)}&entity=musicArtist&limit=200`
    const res = await fetch(url)
    if (!res.ok) continue
    const data = await res.json()
    for (const r of data.results || []) {
      const n = (r.artistName || '').trim()
      if (n && !seen.has(n.toLowerCase())) {
        seen.add(n.toLowerCase())
        names.push(n)
        if (names.length >= 500) break
      }
    }
    await new Promise((r) => setTimeout(r, 250))
  }
  return names.slice(0, 500)
}

async function fetchColleges() {
  const url =
    'https://raw.githubusercontent.com/Hipo/university-domains-list/master/world_universities_and_domains.json'
  const res = await fetch(url)
  if (!res.ok) throw new Error(`College list fetch ${res.status}`)
  const all = await res.json()
  const seen = new Set()
  const out = []
  for (const row of all) {
    if (row?.country !== 'United States') continue
    const n = (row.name || '').trim()
    if (!n || seen.has(n.toLowerCase())) continue
    seen.add(n.toLowerCase())
    out.push(n)
    if (out.length >= 500) break
  }
  return out
}

