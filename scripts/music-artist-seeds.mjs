/**
 * Priority artist names merged first in fetch-fandom-intake-lists (before iTunes API).
 * Order: worldwide headliners → regional intl seeds → deep US/global commercial catalog.
 */

function mergeArtistSeedLists(...lists) {
  const seen = new Set()
  const out = []
  for (const list of lists) {
    for (const raw of list) {
      const t = (raw || '').trim()
      if (!t) continue
      const k = t.toLowerCase()
      if (seen.has(k)) continue
      seen.add(k)
      out.push(t)
    }
  }
  return out
}

